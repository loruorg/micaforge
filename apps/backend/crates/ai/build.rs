//! Find the analyst's tools.
//!
//! Every file in `src/tools/` other than `mod.rs` is one tool, and it exposes
//! `pub fn tool() -> Box<dyn crate::tools::Tool>`. This script lists those
//! files and writes the module declarations and the registry constructor that
//! `src/tools/mod.rs` includes, so adding a tool is adding one file: no list to
//! edit, and so no list for two people adding tools at once to collide on.
//!
//! The order is the file names' order, which keeps the tool list the model is
//! shown stable from one build to the next.

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("cargo sets this"));
    let dir = manifest.join("src").join("tools");
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut names: Vec<String> = fs::read_dir(&dir)
        .expect("src/tools exists")
        .filter_map(|entry| entry.ok())
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "rs"))
        .filter_map(|path| {
            let stem = path.file_stem()?.to_str()?.to_string();
            (stem != "mod").then_some(stem)
        })
        .collect();
    names.sort();

    let mut out = String::from("// Generated by build.rs from the files in src/tools.\n\n");
    for name in &names {
        let path = dir.join(format!("{name}.rs"));
        println!("cargo:rerun-if-changed={}", path.display());
        out.push_str(&format!(
            "#[path = {:?}]\nmod {name};\n",
            path.display().to_string()
        ));
    }
    out.push_str("\n/// Every built-in tool, one per file in `src/tools`, in file-name order.\n");
    out.push_str("fn discovered() -> Vec<Box<dyn Tool>> {\n    vec![\n");
    for name in &names {
        out.push_str(&format!("        {name}::tool(),\n"));
    }
    out.push_str("    ]\n}\n");

    let target = PathBuf::from(env::var("OUT_DIR").expect("cargo sets this")).join("tools.rs");
    fs::write(target, out).expect("OUT_DIR is writable");
}
